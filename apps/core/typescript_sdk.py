"""Generate a frontend-local typed HTTP client from the *selected client's* OpenAPI.

All Node tooling is owned and pinned by the frontend, never a Django runtime
dependency. No remote OpenAPI URL or npx package download is accepted.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

CLIENT_TS = """// Generated by PrimaryKit from this project's OpenAPI schema.
// Add authentication/refresh via a client-owned middleware; do not persist JWTs here.
import createClient from "openapi-fetch";
import type { paths } from "./schema";

export function createPrimaryKitClient(baseUrl: string) {
  return createClient<paths>({ baseUrl });
}
"""


def generate_typescript_sdk(
    *,
    project: Path,
    frontend: Path,
    output: Path,
    schema: Path | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> int:
    """Return a process exit code; schema/Node failures must never publish partial output."""
    project = project.expanduser().resolve()
    frontend = frontend.expanduser().resolve()
    target = (frontend / output).resolve()
    if not target.is_relative_to(frontend):
        raise ValueError("SDK output must be inside the explicitly selected frontend root")
    if not (project / "manage.py").is_file():
        raise ValueError("Expected a Django project with manage.py")
    if not (frontend / "package.json").is_file():
        raise ValueError("Expected an initialized frontend with package.json")
    schema_file = None
    if schema is not None:
        schema_file = (project / schema).expanduser().resolve()
        if not schema_file.is_file() or schema_file.suffix.lower() not in {".yaml", ".yml", ".json"}:
            raise ValueError("OpenAPI schema must be an existing local YAML or JSON file")
    output_files = (target / "schema.d.ts", target / "client.ts")
    if not force and any(path.exists() for path in output_files):
        raise ValueError("SDK files already exist; use --force to explicitly regenerate")

    plan = {
        "project": str(project),
        "frontend": str(frontend),
        "output": str(target),
        "schema_source": str(schema_file) if schema_file else "manage.py spectacular",
        "files": [path.name for path in output_files],
        "external_packages": ["openapi-typescript (frontend dev dependency)", "openapi-fetch"],
        "overwrites": force,
    }
    if dry_run:
        print(json.dumps(plan, ensure_ascii=False, indent=2))
        return 0

    binary = (
        frontend / "node_modules" / ".bin" /
        ("openapi-typescript.cmd" if os.name == "nt" else "openapi-typescript")
    )
    if not binary.is_file():
        raise ValueError(
            "Install pinned frontend dependencies first: "
            "npm install openapi-fetch && npm install -D openapi-typescript"
        )

    # Stage both artifacts before touching the requested frontend output directory.
    with TemporaryDirectory(prefix=".primarykit-sdk-", dir=frontend) as temporary:
        stage = Path(temporary)
        if schema_file is None:
            schema_file = stage / "openapi.yaml"
            subprocess.run(
                [
                    sys.executable,
                    "manage.py",
                    "spectacular",
                    "--file",
                    str(schema_file),
                    "--format",
                    "openapi",
                ],
                cwd=project,
                check=True,
            )
            if not schema_file.is_file() or not schema_file.stat().st_size:
                raise RuntimeError("Django generated an empty OpenAPI schema")

        subprocess.run(
            [str(binary), str(schema_file), "-o", str(stage / "schema.d.ts")],
            cwd=frontend,
            check=True,
        )
        generated = stage / "schema.d.ts"
        if not generated.is_file() or not generated.stat().st_size:
            raise RuntimeError("openapi-typescript returned no generated types")

        (stage / "client.ts").write_text(CLIENT_TS, encoding="utf-8")
        target.mkdir(parents=True, exist_ok=True)
        # Abort if a concurrent actor has created an output between preflight and publish.
        if not force and any(path.exists() for path in output_files):
            raise ValueError("SDK output changed during generation; no files overwritten")
        for name in ("schema.d.ts", "client.ts"):
            shutil.copyfile(stage / name, target / name)
    print(f"Generated typed frontend client: {target}")
    print("Use createPrimaryKitClient(baseUrl); configure client-specific auth middleware.")
    return 0
